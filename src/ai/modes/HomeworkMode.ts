export class HomeworkMode {
  public static getInstructions(hintLevel = 1, userRequestedSolution = false): string {
    if (userRequestedSolution) {
      return [
        `=== نمط الواجبات (Homework Mode) - تقديم الحل الكامل ===`,
        `- طلب الطالب الحل الكامل صراحة بعد المحاولة.`,
        `- قدم الحل التفصيلي خطوة بخطوة مع توضيح الفكرة المفتاحية في النهاية.`,
      ].join("\n");
    }

    if (hintLevel <= 1) {
      return [
        `=== نمط الواجبات (Homework Mode) - التلميح الأول ===`,
        `- لا تكشف الإجابة النهائية أو خطوات الحل الكاملة إطلاقاً!`,
        `- قدم تلميحاً ذكياً أول يوجه تفكير الطالب إلى الخطوة الأولى أو المتغير المفتاحي.`,
        `- شجع الطالب على التجربة والرد بعد التفكير.`,
      ].join("\n");
    }

    return [
      `=== نمط الواجبات (Homework Mode) - التلميح الثاني ===`,
      `- قدم تلميحاً إضافياً يوضح القانون أو الخوارزمية المستهدفة دون إعطاء الأرقام النهائية.`,
      `- اسأل الطالب عن النتيجة التي وصل إليها.`,
    ].join("\n");
  }
}
