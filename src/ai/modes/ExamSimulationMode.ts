export class ExamSimulationMode {
  public static getInstructions(isEvaluation = false): string {
    if (isEvaluation) {
      return [
        `=== نمط الامتحان التجريبي (Exam Mode) - تقييم ورقة الإجابة ===`,
        `- قدم تصحيحاً تفصيلياً لورقة امتحان الطالب وتوزيع الدرجات.`,
        `- اذكر الدرجة الكلية والنسبة المئوية.`,
        `- قدم نصائح تحسين محددة للأسئلة التي خسر الطالب درجات فيها.`,
      ].join("\n");
    }

    return [
      `=== نمط الامتحان التجريبي (Exam Mode) - توليد أسئلة الامتحان ===`,
      `- أنشئ أسئلة امتحان تجريبي مطابقة لنمط امتحانات المادة والمرحلة الدراسية.`,
      `- طابق مستوى الصعوبة المطلوب.`,
      `- لا تكشف الإجابات أو النموذج فوراً؛ انتظر تسليم الطالب للإجابات.`,
    ].join("\n");
  }
}
