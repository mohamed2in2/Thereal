export class QuizMode {
  public static getInstructions(isEvaluation = false): string {
    if (isEvaluation) {
      return [
        `=== نمط الكويز (Quiz Mode) - تقييم إجابة الطالب ===`,
        `- قيم إجابة الطالب فورياً (صحيحة / خاطئة).`,
        `- اشرح سبب الخطأ إن وجد بوضوح.`,
        `- اضبط المستوى والسهولة للأسئلة التالية بناءً على النتيجة.`,
      ].join("\n");
    }

    return [
      `=== نمط الكويز (Quiz Mode) - عرض سؤال واحد ===`,
      `- اعرض سؤالاً واحداً فقط في كل مرة.`,
      `- لا تقدم الإجابة الصحيحة في نفس الرسالة؛ انتظر إجابة الطالب.`,
      `- وفر 4 خيارات (أ، ب، ج، د) واضحة.`,
    ].join("\n");
  }
}
